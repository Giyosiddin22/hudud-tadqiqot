/* ═══════════════════════════════════════════════════════
   LANG — til boshqaruvchi obyekt
   ═══════════════════════════════════════════════════════ */
window.LANG = {
  current: localStorage.getItem('site_lang') || 'uz-lat',

  /* Til o'rnatish */
  set(lang) {
    this.current = lang;
    localStorage.setItem('site_lang', lang);
    this.apply();
  },

  /* Krill ↔ Lotin almashtirish */
  toggleScript() {
    this.set(this.current === 'uz-cyr' ? 'uz-lat' : 'uz-cyr');
  },

  /* UZ tugmasi bosilganda */
  setUz() {
    if (!this.current.startsWith('uz')) this.set('uz-lat');
  },

  /* Tarjima qiymatini olish */
  t(key) {
    return (window.I18N[this.current] || window.I18N['uz-lat'])[key] ?? '';
  },

  /* Sahifaga qo'llash */
  apply() {
    const t = window.I18N[this.current] || window.I18N['uz-lat'];

    // Matn
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const v = t[el.dataset.i18n];
      if (v !== undefined) el.textContent = v;
    });
    // HTML (em teglari uchun)
    document.querySelectorAll('[data-i18n-html]').forEach(el => {
      const v = t[el.dataset.i18nHtml];
      if (v !== undefined) el.innerHTML = v;
    });
    // Placeholder
    document.querySelectorAll('[data-i18n-ph]').forEach(el => {
      const v = t[el.dataset.i18nPh];
      if (v !== undefined) el.placeholder = v;
    });

    const isUz = this.current.startsWith('uz');

    // Til tugmalari holati
    document.querySelectorAll('.ls-btn').forEach(btn => {
      const active = (btn.dataset.lang === 'uz' && isUz) || btn.dataset.lang === this.current;
      btn.classList.toggle('ls-on', active);
    });

    // Admin panelida "Tillar boshqaruvi" bo'limida o'chirilgan tillarni
    // til-almashtirgichda yashirish (backend orqali, /api/langs).
    if (window._disabledLangs && window._disabledLangs.length) {
      document.querySelectorAll('.ls-btn[data-lang]').forEach(btn => {
        if (window._disabledLangs.includes(btn.dataset.lang)) btn.style.display = 'none';
      });
      // Agar foydalanuvchi hozir turgan til admin tomonidan o'chirilgan bo'lsa,
      // uni "ko'rinmas" holatda ushlab qolmaslik uchun birinchi yoqilgan tilga
      // avtomatik o'tkazamiz (aks holda til tugmasi yashirilib, chiqib ketishning
      // iloji qolmaydi).
      if (window._disabledLangs.includes(this.current)) {
        const fallback = ['uz-lat', 'uz-cyr', 'ru', 'en'].find(c => !window._disabledLangs.includes(c));
        if (fallback && fallback !== this.current) { this.set(fallback); return; }
      }
    }

    // Krill/Lotin tugmasi
    document.querySelectorAll('.ls-script').forEach(btn => {
      btn.style.display = isUz ? '' : 'none';
      btn.textContent   = this.current === 'uz-cyr' ? 'Lotin' : 'Крил';
    });

    // Til dropdown (lang-dd) — bosh sahifadagi yangi dizayn
    document.querySelectorAll('.lang-dd-item').forEach(item => {
      const on = item.dataset.lc === this.current;
      item.classList.toggle('on', on);
      if (window._disabledLangs && window._disabledLangs.includes(item.dataset.lc)) {
        item.style.display = 'none';
      } else {
        item.style.display = '';
      }
    });
    document.querySelectorAll('#lang-dd-code').forEach(el => {
      el.textContent = this.current === 'uz-cyr' ? 'ЎЗ' : this.current.toUpperCase().slice(0, 2);
    });

    document.documentElement.lang = isUz ? 'uz' : this.current;

    // Sahifaga xos qayta render
    if (typeof window._onLangChange === 'function') window._onLangChange();
  }
};

/* Sahifa yuklanganda avtomatik qo'llash — avval backenddan o'chirilgan
   tillar ro'yxatini olib kelamiz, so'ng birinchi marta qo'llaymiz. */
window._disabledLangs = [];
async function _loadDisabledLangs() {
  try {
    const r = await fetch('/api/langs');
    if (r.ok) {
      const langs = await r.json();
      window._disabledLangs = langs.filter(l => !l.enabled).map(l => l.code);
    }
  } catch (e) { /* backend unreachable — treat all languages as enabled */ }
}
document.addEventListener('DOMContentLoaded', async () => {
  await _loadDisabledLangs();
  LANG.apply();
});
